def list_students():
    """
    列出所有学生
    
    【作用】：显示系统中所有学生的信息表格
    【知识点】：格式化输出、字符串的格式化方法
    """
    
    print("\n--- 所有学生信息 ---")
    
    # 【知识点32】检查列表是否为空
    # not students：如果列表是空的，结果为True
    # 空列表在Python中被视为"假"，not [] = True
    if not students:
        print("当前没有学生信息！")
        return
    
    # 【知识点33】字符串格式化：< 左对齐，指定宽度
    # f"{'姓名':<10}"：让"姓名"占10个字符宽度，左对齐
    # 如果内容不足10个字符，右边用空格填充
    # 例如："姓名"只有2个字符，输出时会变成"姓名        "（后面8个空格）
    # 这样可以让表格各列对齐
    print(f"{'姓名':<10}{'语文':<10}{'数学':<10}{'英语':<10}")
    
    # 打印分隔线
    print("-" * 40)
    
    # 遍历所有学生，打印每个学生的信息
    for s in students:
        # 每个学生的信息格式化输出
        # s['name']可能是中文，中文字符宽度需要注意
        print(f"{s['name']:<10}{s['chinese']:<10}{s['math']:<10}{s['english']:<10}")


