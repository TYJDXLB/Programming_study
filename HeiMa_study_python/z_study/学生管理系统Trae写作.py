# 函数6：delete_student() - 删除学生信息
# ------------------------------------------------------------
def delete_student():
    """
    删除学生信息
    
    【作用】：根据姓名找到学生，从列表中删除
    【知识点】：enumerate()函数、列表的pop()方法
    """
    
    print("\n--- 删除学生信息 ---")
    
    name = input("请输入要删除的学生姓名：").strip()
    
    # 【知识点29】enumerate()函数：同时获取索引和元素
    # enumerate(列表)返回：(索引, 元素) 的序列
    # 例如：students = ["张三", "李四"]
    # for i, s in enumerate(students):
    #     第一次循环：i=0, s="张三"
    #     第二次循环：i=1, s="李四"
    # 
    # 为什么需要索引？因为删除列表元素需要知道位置（索引）
    for i, s in enumerate(students):
        
        if s["name"] == name:  # 找到该学生
            
            # 【知识点30】列表的pop()方法：删除指定位置的元素
            # pop(索引)：删除列表中该索引位置的元素，并返回被删除的元素
            # 例如：students = ["张三", "李四", "王五"]
            # students.pop(1) 会删除"李四"，列表变成["张三", "王五"]
            students.pop(i)  # 删除索引i位置的学生
            
            # 保存到CSV文件
            save_to_csv()
            
            print(f"学生【{name}】删除成功！")
            return  # 删除完成，结束函数
    
    print(f"未找到学生【{name}】，请检查姓名！")


