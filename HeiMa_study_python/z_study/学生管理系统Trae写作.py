# 函数1：load_from_csv() - 从CSV文件加载学生数据
# ------------------------------------------------------------
def load_from_csv():
    """
    从 CSV 文件加载学生数据，如果文件不存在则跳过
    
    【作用】：程序启动时，读取之前保存的学生数据
    【参数】：无参数（不需要传入任何数据）
    【返回值】：无返回值，但会把数据加载到全局变量students列表中
    """
    
    # 【知识点7】os.path.exists(路径)：检查文件是否存在
    # 返回True表示文件存在，返回False表示文件不存在
    if not os.path.exists(CSV_FILE):  # 如果CSV文件不存在
        return  # 直接返回，不执行后面的代码（return可以提前结束函数）
    
    # 【知识点8】open()函数：打开文件
    # 格式：open(文件路径, 模式, 其他参数)
    # 常用模式：
    #   "r" - 读取模式（read）
    #   "w" - 写入模式（write），会覆盖原有内容
    #   "a" - 追加模式（append），在文件末尾添加内容
    # newline=""：让Python不自动处理换行符，避免出现空行
    # encoding="utf-8-sig"：指定文件编码为UTF-8（支持中文），sig表示带BOM头（Excel兼容更好）
    
    # 【知识点9】with语句：自动管理文件资源
    # with open(...) as f:
    #     操作文件
    # with语句会在代码块结束后自动关闭文件，即使发生错误也会关闭
    # 这比手动调用 f.close() 更安全，推荐始终使用with语句操作文件
    with open(CSV_FILE, "r", newline="", encoding="utf-8-sig") as f:
        
        # 【知识点10】csv.DictReader：按行读取CSV文件，每行变成一个字典
        # 普通的csv.reader返回列表，如 ['张三', '90', '85']
        # csv.DictReader返回字典，如 {'姓名': '张三', '语文': '90', ...}
        # 字典的键就是CSV文件的表头（第一行）
        reader = csv.DictReader(f)
        
        # 【知识点11】for循环：遍历序列中的每个元素
        # 格式：for 变量 in 序列:
        #       循环体
        # reader是一个迭代器，每次迭代返回一行数据（一个字典）
        for row in reader:  # row是每一行的数据，是一个字典
            
            # 【知识点12】创建字典：用花括号 {}
            # 从row字典中取出各科成绩，转换成浮点数（小数）
            # row["姓名"]：用键访问字典中的值
            # float()函数：把字符串转换成浮点数，如 float("90") 得到 90.0
            student = {
                "name": row["姓名"],      # 学生姓名（字符串，不需要转换）
                "chinese": float(row["语文"]),  # 语文成绩（转换成数字）
                "math": float(row["数学"]),      # 数学成绩
                "english": float(row["英语"]),   # 英语成绩
            }
            
            # 【知识点13】列表的append()方法：在列表末尾添加一个元素
            # students.append(student)：把student字典添加到students列表中
            students.append(student)


# ------------------------------------------------------------
# 函数2：save_to_csv() - 把学生数据保存到CSV文件
# ------------------------------------------------------------
def save_to_csv():
    """
    将当前所有学生数据保存到 CSV 文件
    
    【作用】：每次添加、修改、删除学生后，把最新数据保存到文件
    【参数】：无参数（直接使用全局变量students）
    【返回值】：无返回值
    """
    
    # 打开文件，使用"w"写入模式（会覆盖原有内容）
    with open(CSV_FILE, "w", newline="", encoding="utf-8-sig") as f:
        
        # 【知识点14】csv.writer：创建一个CSV写入器
        # 用于把数据写入CSV文件
        writer = csv.writer(f)
        
        # 【知识点15】writerow()方法：写入一行数据
        # 参数是一个列表，列表中的每个元素会成为CSV中的一列
        # 这行代码写入表头：姓名,语文,数学,英语
        writer.writerow(["姓名", "语文", "数学", "英语"])
        
        # 遍历students列表中的每个学生字典
        for s in students:  # s是每个学生的字典
            
            # 把字典中的数据提取出来，组成一个列表，写入CSV的一行
            # 例如：["张三", 90, 85, 88] 会变成 CSV中的：张三,90,85,88
            writer.writerow([s["name"], s["chinese"], s["math"], s["english"]])


