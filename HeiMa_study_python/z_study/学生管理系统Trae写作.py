# 函数9：statistics() - 统计班级成绩
# ------------------------------------------------------------
def statistics():
    """
    统计班级成绩
    
    【作用】：计算各科的最高分、最低分、平均分，以及对应的学生姓名
    【知识点】：列表推导式、max/min/sum函数、字符串的join方法
    """
    
    print("\n--- 班级成绩统计 ---")
    
    if not students:
        print("当前没有学生信息，无法统计！")
        return
    
    # 【知识点34】元组（Tuple）：用圆括号 () 表示，不可变的列表
    # 元组和列表类似，但元组创建后不能修改
    # 这里用元组列表存储科目信息：(显示名称, 字典键名)
    subjects = [("语文", "chinese"), ("数学", "math"), ("英语", "english")]
    
    # 【知识点35】for循环解包元组
    # for label, key in subjects：
    # 每次循环从元组中取出两个值，分别赋给label和key
    # 第一次：label="语文", key="chinese"
    # 第二次：label="数学", key="math"
    # 第三次：label="英语", key="english"
    for label, key in subjects:
        
        # 【知识点36】列表推导式（List Comprehension）：简洁地创建列表
        # 格式：[表达式 for 变量 in 序列]
        # 例如：[s[key] for s in students]
        # 意思是：对于students中的每个s，取出s[key]，组成一个新列表
        # 
        # 这行代码：取出所有学生的某科成绩，组成一个列表
        # 例如：如果key="chinese"，得到 [90, 78, 85, ...]（所有语文成绩）
        scores = [s[key] for s in students]
        
        # 【知识点37】max()、min()、sum()函数
        # max(列表)：返回列表中的最大值
        # min(列表)：返回列表中的最小值
        # sum(列表)：返回列表中所有元素的和
        max_score = max(scores)   # 最高分
        min_score = min(scores)   # 最低分
        
        # 【知识点38】len()函数：获取列表长度（元素个数）
        # len(students)：返回students列表中有多少个学生
        # 平均分 = 总分 / 人数
        avg_score = sum(scores) / len(scores)
        
        # 【知识点39】带条件的列表推导式
        # 格式：[表达式 for 变量 in 序列 if 条件]
        # 例如：[s["name"] for s in students if s[key] == max_score]
        # 意思是：对于students中的每个s，如果s[key]等于max_score，就取出s["name"]
        # 
        # 这行代码：找出所有最高分的学生姓名（可能有多个学生并列最高分）
        max_names = [s["name"] for s in students if s[key] == max_score]
        
        # 找出所有最低分的学生姓名
        min_names = [s["name"] for s in students if s[key] == min_score]
        
        # 【知识点40】字符串的join()方法：连接列表中的字符串
        # "分隔符".join(字符串列表)：把列表中的字符串用分隔符连接成一个字符串
        # 例如：['张三', '李四'] 用 '、' 连接，得到 "张三、李四"
        # 
        # 这行代码：把所有最高分学生的姓名用顿号连接
        print(f"\n【{label}】")
        print(f"  最高分：{max_score}（学生：{'、'.join(max_names)}）")
        print(f"  最低分：{min_score}（学生：{'、'.join(min_names)}）")
        
        # 【知识点41】格式化数字的小数位数
        # f"{avg_score:.2f}"：保留2位小数
        # .2f 表示：浮点数，保留2位小数
        # 例如：avg_score = 85.666...，输出时会显示 85.67
        print(f"  平均分：{avg_score:.2f}")


