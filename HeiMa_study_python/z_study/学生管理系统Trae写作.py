# 函数4：add_student() - 添加学生信息
# ------------------------------------------------------------
def add_student():
    """
    添加学生信息
    
    【作用】：让用户输入学生姓名和三科成绩，添加到系统中
    【流程】：
    1. 输入姓名
    2. 检查姓名是否为空、是否已存在
    3. 输入三科成绩
    4. 创建学生字典，添加到列表
    5. 保存到CSV文件
    """
    
    print("\n--- 添加学生信息 ---")
    
    # 【知识点19】input()函数：获取用户输入
    # input(提示文字)：在屏幕显示提示，等待用户输入，返回用户输入的字符串
    # 例如：用户输入"张三"，name变量就会得到"张三"
    name = input("请输入学生姓名：")
    
    # 【知识点20】字符串的strip()方法：去除首尾空白字符
    # strip()会去掉字符串开头和结尾的空格、制表符、换行符等
    # 例如："  张三  ".strip() 得到 "张三"
    # 这样可以防止用户不小心输入了多余的空格
    name = name.strip()
    
    # 【知识点21】if条件判断
    # 格式：if 条件:
    #       条件为True时执行的代码
    # not name：如果name是空字符串""，not ""的结果是True
    # 空字符串在Python中被视为"假"（False），not False = True
    if not name:  # 如果姓名为空
        print("姓名不能为空！")
        return  # 提前结束函数，不执行后面的代码
    
    # 【知识点22】for循环遍历列表
    # 检查学生是否已经存在（避免重复添加）
    for s in students:  # s是列表中的每个元素（每个学生的字典）
        
        # 【知识点23】用键访问字典的值
        # s["name"]：从字典s中取出name对应的值
        # ==：比较两个值是否相等
        if s["name"] == name:  # 如果找到同名学生
            # 【知识点24】f-string格式化字符串（Python 3.6+推荐用法）
            # f"文本{变量}"：在字符串中嵌入变量的值
            # 例如：name="张三"，f"学生【{name}】" 得到 "学生【张三】"
            print(f"学生【{name}】已存在，请勿重复添加！")
            return  # 提前结束函数
    
    # 【知识点25】try-except异常处理
    # 用于处理可能发生的错误
    # 格式：
    #   try:
    #       可能出错的代码
    #   except 错误类型:
    #       出错后执行的代码
    # 
    # 这里用try-except是因为用户可能输入非数字（如输入"abc"作为成绩）
    # float("abc")会抛出ValueError错误，我们用except捕获这个错误
    try:
        # 输入三科成绩，并用float()转换成数字
        chinese = float(input("请输入语文成绩："))
        math = float(input("请输入数学成绩："))
        english = float(input("请输入英语成绩："))
    
    except ValueError:  # 如果转换失败（用户输入的不是数字）
        print("成绩输入有误，请输入数字！")
        return  # 提前结束函数
    
    # 【知识点26】创建字典并添加到列表
    # 创建一个学生字典，包含姓名和三科成绩
    student = {
        "name": name,        # 姓名
        "chinese": chinese,  # 语文成绩
        "math": math,        # 数学成绩
        "english": english,  # 英语成绩
    }
    
    # 把新学生添加到列表末尾
    students.append(student)
    
    # 保存到CSV文件（持久化存储）
    save_to_csv()
    
    print(f"学生【{name}】添加成功！")


