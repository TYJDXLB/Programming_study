# 函数5：modify_student() - 修改学生信息
# ------------------------------------------------------------
def modify_student():
    """
    修改学生信息
    
    【作用】：根据姓名找到学生，更新其三科成绩
    【流程】：
    1. 输入要修改的学生姓名
    2. 在列表中查找该学生
    3. 如果找到，输入新成绩并更新
    4. 如果没找到，提示用户
    """
    
    print("\n--- 修改学生信息 ---")
    
    # 输入要修改的学生姓名
    name = input("请输入要修改的学生姓名：").strip()
    
    # 【知识点27】for循环查找元素
    # 遍历列表，寻找匹配的学生
    for s in students:
        
        if s["name"] == name:  # 如果找到该学生
            
            # 用try-except处理可能的输入错误
            try:
                chinese = float(input("请输入新的语文成绩："))
                math = float(input("请输入新的数学成绩："))
                english = float(input("请输入新的英语成绩："))
            except ValueError:
                print("成绩输入有误，请输入数字！")
                return  # 输入错误，提前结束
            
            # 【知识点28】修改字典中的值
            # 直接用键赋值：字典[键] = 新值
            # 这会更新字典中该键对应的值
            s["chinese"] = chinese  # 更新语文成绩
            s["math"] = math        # 更新数学成绩
            s["english"] = english  # 更新英语成绩
            
            # 保存到CSV文件
            save_to_csv()
            
            print(f"学生【{name}】信息修改成功！")
            return  # 修改完成，结束函数
    
    # 如果for循环结束还没找到学生（没有执行return），说明学生不存在
    print(f"未找到学生【{name}】，请检查姓名！")


